const dicts: Record<I18n, Dict> = { en, hi, gu, 'hi-latn': hiLatn, 'gu-latn': guLatn };

export const translate = (locale: I18n, key: string, vars?: Vars): string => {
  const entry = dicts[locale]?.[key] ?? dicts.en[key];
  if (entry == null) return key;
  return typeof entry === 'function' ? entry(vars || {}) : entry;
};

export const useT = () => {
  const { language } = useConfig();
  const locale = (language as I18n) || 'en';
  return useCallback((key: string, vars?: Vars) => translate(locale, key, vars), [locale]);
};
